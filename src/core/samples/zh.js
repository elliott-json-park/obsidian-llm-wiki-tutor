// AGENTS.md 의 노트 형식: 제목 · 一句话 · 食材 · 内容 (· 例子)
function page(title, line, raws, body, example) {
  let s = `# ${title}\n\n## 一句话\n${line}\n\n## 食材\n${raws.map((r) => `- ${r}`).join('\n')}\n\n## 内容\n${body.trim()}\n`;
  if (example) s += `\n## 例子\n${example.trim()}\n`;
  return s;
}

